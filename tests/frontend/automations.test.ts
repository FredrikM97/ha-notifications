import { afterEach, describe, expect, it, vi } from "vitest";
import {
  deleteAlert,
  reloadAutomations,
  saveAlert,
  saveConfiguration,
} from "../../frontend/automations.js";
import type { AutomationChanges, HaConfig } from "../../frontend/types.js";
import { configuredAlertFixture, createHassClient } from "./conftest.js";

const description = "Generated by HA Notifications. Do not edit manually.";
const changes: AutomationChanges = { upsert: [], delete: [], description };
afterEach(() => vi.useRealTimers());

function document(id: string, alias = id): HaConfig {
  return { id: `ha_notifications_${id}`, description, alias };
}

function automationClient(
  operations: AutomationChanges = changes,
  stored: HaConfig[] = [],
) {
  const client = createHassClient();
  client.hass.user = { is_admin: true };
  const documents = new Map(stored.map((item) => [item.id, item]));
  const loaded = new Map(documents);
  function states() {
    return [...loaded].map(([id, config]) => ({
      entity_id: `automation.${id}_renamed`,
      state: config.initial_state === false ? "off" : "on",
      attributes: { id },
    }));
  }
  client.callWS.mockImplementation(async (message) => {
    if (message.type === "get_states") return states();
    if (message.type === "automation/config") {
      const state = states().find(item => item.entity_id === message.entity_id);
      if (!state) throw { code: "not_found" };
      return { config: loaded.get(state.attributes.id) };
    }
    if (message.type === "call_service") {
      const { id } = message.service_data as { id: string };
      loaded.set(id, documents.get(id)!);
      return {};
    }
    if (message.type === "ha_notifications/get_automations") return operations;
    return {
      saved: true,
      config: message.config ?? { version: 1, alerts: message.alert ? [message.alert] : [] },
      automation_changes: operations,
    };
  });
  client.callApi.mockImplementation(async (method, path, payload) => {
    const id = decodeURIComponent(path.split("/").at(-1)!);
    if (method === "GET") {
      if (!documents.has(id)) throw { status_code: 404 };
      return documents.get(id);
    }
    if (method === "POST") {
      documents.set(id, payload);
      loaded.set(id, payload);
    }
    if (method === "DELETE") {
      documents.delete(id);
      loaded.delete(id);
    }
    return { result: "ok" };
  });
  return { ...client, documents, loaded, states };
}

describe("automation API operations", () => {
  it("verifies unchanged ordinary saves without writing or requesting another reload", async () => {
    const automation = document("door");
    const client = automationClient({ ...changes, upsert: [automation] }, [automation]);

    await saveConfiguration(client.hass, {});

    expect(client.callApi).toHaveBeenCalledExactlyOnceWith(
      "GET", `config/automation/config/${automation.id}`, undefined,
    );
    expect(client.callWS.mock.calls.some(([message]) => message.type === "call_service")).toBe(false);
    expect(client.callWS).toHaveBeenCalledWith({
      type: "automation/config", entity_id: `automation.${automation.id}_renamed`,
    });
  });

  it("targets unchanged automations on explicit Reload without rewriting their documents", async () => {
    const first = document("first");
    const second = document("second");
    const client = automationClient(
      { ...changes, upsert: [first, second] },
      [{ alias: first.alias, description, id: first.id }, second],
    );

    await reloadAutomations(client.hass);

    expect(client.callApi.mock.calls).toEqual([
      ["GET", `config/automation/config/${first.id}`, undefined],
      ["GET", `config/automation/config/${second.id}`, undefined],
    ]);
    expect(client.callWS.mock.calls.filter(([message]) => message.type === "call_service")).toEqual(
      [first, second].map(item => [{
        type: "call_service", domain: "automation", service: "reload",
        service_data: { id: item.id },
      }]),
    );
  });

  it("reloads only the changed ID through its config API update, including on repeated Reload", async () => {
    const first = document("first");
    const updated = document("second", "Updated");
    const client = automationClient(
      { ...changes, upsert: [first, updated] }, [first, document("second")],
    );

    await reloadAutomations(client.hass);
    await reloadAutomations(client.hass);

    expect(client.callApi.mock.calls.filter(([method]) => method !== "GET")).toEqual([
      ["POST", `config/automation/config/${updated.id}`, updated],
    ]);
    expect(client.callWS.mock.calls.filter(([message]) => message.type === "call_service")
      .map(([message]) => message.service_data)).toEqual([
      { id: first.id }, { id: first.id }, { id: updated.id },
    ]);
  });

  it("recovers a stored but unloaded automation using only a targeted reload", async () => {
    const automation = document("door");
    const unrelated = document("unrelated");
    const client = automationClient({ ...changes, upsert: [automation] }, [automation, unrelated]);
    client.loaded.delete(automation.id);

    await reloadAutomations(client.hass);

    expect(client.loaded.get(automation.id)).toEqual(automation);
    expect(client.callApi.mock.calls.every(([method]) => method === "GET")).toBe(true);
    expect(client.callWS).toHaveBeenCalledWith({
      type: "call_service", domain: "automation", service: "reload",
      service_data: { id: automation.id },
    });
    expect(client.callWS).toHaveBeenCalledWith({
      type: "automation/config", entity_id: `automation.${automation.id}_renamed`,
    });
    expect(client.callWS.mock.calls.filter(([message]) => message.type === "call_service")).toHaveLength(1);
  });

  it("waits for the complete updated configuration rather than the previous loaded entity", async () => {
    vi.useFakeTimers();
    const old = document("door");
    const updated = document("door", "Updated");
    const client = automationClient({ ...changes, upsert: [updated] }, [old]);
    const transport = client.callApi.getMockImplementation()!;
    client.callApi.mockImplementation(async (...args) => {
      const result = await transport(...args);
      if (args[0] === "POST") client.loaded.set(old.id, old);
      return result;
    });
    let completed = false;
    const saving = saveConfiguration(client.hass, {}).then(() => { completed = true; });
    await vi.advanceTimersByTimeAsync(500);
    expect(completed).toBe(false);
    client.loaded.set(updated.id, updated);
    await vi.advanceTimersByTimeAsync(250);
    await saving;
    expect(completed).toBe(true);
    expect(vi.getTimerCount()).toBe(0);
  });

  it.each(["missing", "unavailable", "stale", "stalled request"])(
    "reports successful API persistence but %s runtime after a bounded wait",
    async (failure) => {
      vi.useFakeTimers();
      const automation = document("door");
      const client = automationClient({ ...changes, upsert: [automation] });
      const transport = client.callWS.getMockImplementation()!;
      client.callWS.mockImplementation(async message => {
        if (message.type === "get_states") {
          if (failure === "stalled request") return new Promise(() => {});
          if (failure === "missing") return [];
          if (failure === "unavailable") return client.states().map(item => ({ ...item, state: "unavailable" }));
        }
        if (message.type === "automation/config" && failure === "stale") {
          return { config: document("door", "Previous configuration") };
        }
        return transport(message);
      });
      const failed = expect(saveConfiguration(client.hass, {})).rejects.toThrow(
        /Configuration was saved.*did not load.*ha_notifications_door/,
      );

      await vi.advanceTimersByTimeAsync(10_000);
      await failed;

      expect(client.documents.get(automation.id)).toEqual(automation);
      const count = client.callWS.mock.calls.length;
      await vi.advanceTimersByTimeAsync(1000);
      expect(client.callWS).toHaveBeenCalledTimes(count);
      expect(vi.getTimerCount()).toBe(0);
    },
  );

  it("retries an entity disappearing during reload but surfaces permission errors immediately", async () => {
    vi.useFakeTimers();
    const automation = document("door");
    const client = automationClient({ ...changes, upsert: [automation] }, [automation]);
    const transport = client.callWS.getMockImplementation()!;
    let attempts = 0;
    client.callWS.mockImplementation(async message => {
      if (message.type === "automation/config" && attempts++ === 0) throw { code: "not_found" };
      return transport(message);
    });
    const reload = reloadAutomations(client.hass);
    await vi.advanceTimersByTimeAsync(250);
    await reload;
    expect(attempts).toBe(2);
    client.callWS.mockImplementation(async message => {
      if (message.type === "automation/config") throw { code: "unauthorized", message: "Forbidden" };
      return transport(message);
    });
    await expect(reloadAutomations(client.hass)).rejects.toThrow("Forbidden");
    expect(vi.getTimerCount()).toBe(0);
  });

  it.each([
    ["save alert", (client: ReturnType<typeof automationClient>) =>
      saveAlert(client.hass, configuredAlertFixture())],
    ["save YAML", (client: ReturnType<typeof automationClient>) =>
      saveConfiguration(client.hass, {})],
    ["delete alert", (client: ReturnType<typeof automationClient>) =>
      deleteAlert(client.hass, "door")],
    ["reload", (client: ReturnType<typeof automationClient>) =>
      reloadAutomations(client.hass)],
  ] as const)("rejects %s before any transport for non-admin or missing users", async (_name, operation) => {
    for (const user of [{ is_admin: false }, undefined]) {
      const client = automationClient();
      client.hass.user = user;

      await expect(operation(client)).rejects.toThrow("Administrator access is required");

      expect(client.callWS).not.toHaveBeenCalled();
      expect(client.callApi).not.toHaveBeenCalled();
    }
  });

  it("rechecks permission when a queued operation starts", async () => {
    const client = automationClient();
    let release!: (value: unknown) => void;
    client.callWS.mockImplementationOnce(() => new Promise(resolve => { release = resolve; }));
    const first = saveConfiguration(client.hass, {});
    await vi.waitFor(() => expect(client.callWS).toHaveBeenCalledOnce());
    const second = deleteAlert(client.hass, "door");
    const denied = expect(second).rejects.toThrow("Administrator access is required");
    client.hass.user = { is_admin: false };
    release({ saved: true, config: { version: 1, alerts: [] }, automation_changes: changes });

    await first;
    await denied;

    expect(client.callWS).toHaveBeenCalledOnce();
    expect(client.callApi).not.toHaveBeenCalled();
  });

  it("updates only explicit IDs without registry discovery, metadata polling, or deleting unrelated records", async () => {
    const unchanged = document("same");
    const changed = document("changed", "Updated");
    const added = document("new");
    const unowned = { ...document("manual"), description: "User automation" };
    const client = automationClient(
      {
        ...changes,
        upsert: [unchanged, changed, added],
        delete: ["ha_notifications_stale", "ha_notifications_manual"],
      },
      [unchanged, document("changed"), document("stale"), document("unrelated"), unowned],
    );

    await saveConfiguration(client.hass, {});

    expect(client.callApi.mock.calls.filter(([method]) => method !== "GET")).toEqual([
      ["POST", "config/automation/config/ha_notifications_changed", changed],
      ["POST", "config/automation/config/ha_notifications_new", added],
      ["DELETE", "config/automation/config/ha_notifications_stale", undefined],
    ]);
    expect(client.documents.get(unowned.id)).toEqual(unowned);
    expect(client.documents.has("ha_notifications_unrelated")).toBe(true);
    expect(client.callApi.mock.calls.some(([, path]) => path.endsWith("/ha_notifications_unrelated")))
      .toBe(false);
    expect(client.callWS).toHaveBeenCalledWith({
      type: "ha_notifications/save_config", config: {},
    });
  });

  it("checks unloaded automation ownership before any writes", async () => {
    const client = automationClient(
      { ...changes, upsert: [document("new"), document("collision")] },
      [{ ...document("collision"), description: "User automation" }],
    );

    await expect(reloadAutomations(client.hass)).rejects.toThrow("not owned by HA Notifications");
    expect(client.callApi.mock.calls.every(([method]) => method === "GET")).toBe(true);
  });

  it.each([401, 403, 500])("does not treat HTTP %s as a missing automation", async status_code => {
    const client = automationClient({ ...changes, upsert: [document("door")] });
    client.callApi.mockRejectedValueOnce({ status_code, body: { message: "Unavailable" } });

    await expect(reloadAutomations(client.hass)).rejects.toThrow("Unavailable");
    expect(client.callApi).toHaveBeenCalledOnce();
  });

  it.each([
    [document("door"), document("door")],
    [{ ...document("door"), id: "manual" }],
    [{ ...document("door"), description: "Wrong marker" }],
  ])("rejects invalid generated documents before contacting the native API", async (...upsert) => {
    const client = automationClient({ ...changes, upsert });
    await expect(reloadAutomations(client.hass)).rejects.toThrow("unique managed IDs");
    expect(client.callApi).not.toHaveBeenCalled();
  });

  it.each([
    { upsert: [], delete: ["manual"] },
    { upsert: [document("door")], delete: ["ha_notifications_door"] },
  ])("rejects invalid or overlapping deletion IDs before native API calls", async operations => {
    const client = automationClient({ ...changes, ...operations });
    await expect(reloadAutomations(client.hass)).rejects.toThrow("distinct managed IDs");
    expect(client.callApi).not.toHaveBeenCalled();
  });

  it("saves a single complete automation by stable ID, including its saved enablement", async () => {
    const alert = configuredAlertFixture({ enabled: false });
    const automation = { ...document(alert.id), initial_state: false };
    const unrelated = document("window");
    const client = automationClient({ ...changes, upsert: [automation] }, [unrelated]);

    await expect(saveAlert(client.hass, alert)).resolves.toEqual(alert);

    expect(client.callWS).toHaveBeenCalledWith({
      type: "ha_notifications/save_config", alert,
    });
    expect(client.callApi.mock.calls).toEqual([
      ["GET", `config/automation/config/${automation.id}`, undefined],
      ["POST", `config/automation/config/${automation.id}`, automation],
    ]);
    expect(client.documents.get(unrelated.id)).toEqual(unrelated);
  });

  it("uses an explicit delete ID and treats an already-missing automation as deleted", async () => {
    const client = automationClient({ ...changes, delete: ["ha_notifications_door"] });

    await deleteAlert(client.hass, "door");

    expect(client.callWS).toHaveBeenCalledExactlyOnceWith({
      type: "ha_notifications/delete", alert_id: "door",
    });
    expect(client.callApi).toHaveBeenCalledExactlyOnceWith(
      "GET", "config/automation/config/ha_notifications_door", undefined,
    );
  });

  it("reports partial saves and recovers failed deletions only on explicit Reload", async () => {
    const client = automationClient(
      { ...changes, delete: ["ha_notifications_door"] }, [document("door")],
    );
    client.callApi.mockRejectedValueOnce(new Error("Offline"));
    await expect(deleteAlert(client.hass, "door")).rejects.toThrow(
      "Configuration was saved, but the automation API update failed.",
    );
    expect(client.documents.has("ha_notifications_door")).toBe(true);
    expect(client.callWS).toHaveBeenCalledOnce();

    await reloadAutomations(client.hass);

    expect(client.callWS.mock.lastCall).toEqual([{ type: "ha_notifications/get_automations" }]);
    expect(client.documents.size).toBe(0);
  });

  it("serializes explicit operations across callers sharing a transport", async () => {
    const first = configuredAlertFixture({ id: "first" });
    const second = configuredAlertFixture({ id: "second" });
    const client = automationClient();
    const stored: string[] = [];
    client.callWS.mockImplementation(async (message) => {
      const alert = message.alert as typeof first;
      stored.push(alert.id);
      return {
        saved: true, config: { version: 1, alerts: [alert] }, automation_changes: changes,
      };
    });

    await Promise.all([
      saveAlert(client.hass, first),
      saveAlert({ ...client.hass }, second),
    ]);

    expect(stored).toEqual(["first", "second"]);
    expect(client.callWS.mock.calls.map(([message]) => message.type)).toEqual([
      "ha_notifications/save_config", "ha_notifications/save_config",
    ]);
  });
});
